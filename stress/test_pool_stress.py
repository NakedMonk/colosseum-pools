#!/usr/bin/env python3
"""Проверки стресс-теста правил пула (`pool_stress.py`).

Данные синтетические, ответ известен заранее. Каждая проверка названа по правилу, которое держит:
снятие правила обязано её краснить (стенд поломок — `mut_pool_stress.py`).

    python3 test_pool_stress.py
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
import pool_stress as PS                                               # noqa: E402

T0 = 1760054400          # 2025-10-10 00:00 UTC
LEV, DL, MDD, MM, TAKER = 5.0, 0.03, 0.06, 0.02, 4.5
FEE = TAKER / 1e4 * LEV                                                # доля капитала места на закрытие


def bar(rows, t0: int = T0) -> dict:
    """rows: (open, high, low, close) по минутам."""
    a = np.array(rows, dtype=float)
    return {"ts": (t0 + np.arange(len(a)) * 60).astype(np.int64),
            "o": a[:, 0], "h": a[:, 1], "l": a[:, 2], "c": a[:, 3]}


def ep(b, i=0, side=1, *, lag=1, snapshot=100.0, start=100.0, lev=LEV, dl=DL, mdd=MDD, mm=MM,
       exec_mode="open"):
    return PS.episode(b, i, side, lev=lev, daily_loss=dl, max_dd=mdd, snapshot=snapshot,
                      start_eq=start, lag=lag, taker_bps=TAKER, mm=mm, exec_mode=exec_mode)


def close(x: float, y: float, eps: float = 1e-9) -> bool:
    return abs(x - y) <= eps


def write_npz(d: Path, sym: str, rows, t0: int = T0, ts=None) -> None:
    """`ts` — свои отметки минут (так строится ряд с пропущенной минутой); иначе подряд от t0."""
    a = np.array(rows, dtype=float)
    stamps = (t0 + np.arange(len(a)) * 60) if ts is None else np.array(ts)
    np.savez(d / f"{sym}.npz", ts=stamps.astype(np.int64),
             open=a[:, 0], high=a[:, 1], low=a[:, 2], close=a[:, 3], volume=np.ones(len(a)))


def main() -> int:
    fails: list[str] = []
    flat = (100.0, 100.0, 100.0, 100.0)

    # 1. Цена линии: при плече 5 дневной убыток 3 % эквити = 0.6 % цены.
    if not close(PS.line_price(100.0, 1, LEV, DL), 99.4):
        fails.append(f"линия лонга не на 0.6 % ниже входа: {PS.line_price(100.0, 1, LEV, DL)}")
    if not close(PS.line_price(100.0, -1, LEV, DL), 100.6):
        fails.append(f"линия шорта не на 0.6 % выше входа: {PS.line_price(100.0, -1, LEV, DL)}")

    # 2. Идеальный сторож (задержка 0) без гэпа: убыток ровно линия плюс комиссия, перелёта по цене нет.
    #    Минута пробития ЗАКРЫВАЕТСЯ ВЫШЕ линии: правило рубит фитиль, а не закрытие.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), flat])
    r = ep(b, lag=0)
    if not (r["пробито"] and close(r["итог_доля"], -(DL + FEE))):
        fails.append(f"мгновенный сторож теряет не 3 % + комиссия: {r}")
    if not close(r["перелёт_доля"], FEE):
        fails.append(f"перелёт мгновенного сторожа не равен комиссии: {r['перелёт_доля']}")

    # 3. Задержка 1 минута: выход по ОТКРЫТИЮ следующей минуты, убыток = плечо × ход цены.
    #    Открытие и закрытие этой минуты РАЗНЫЕ: выход по закрытию дал бы другое число.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), (95.0, 96.5, 95.0, 96.5)])
    r = ep(b, lag=1)
    if not close(r["итог_доля"], -(LEV * 0.05 + FEE)):
        fails.append(f"задержка 1: выход не по открытию следующей минуты: {r}")
    if not close(r["перелёт_доля"], (1 - DL) - (1 - LEV * 0.05 - FEE)):
        fails.append(f"перелёт считается не от линии: {r['перелёт_доля']}")

    # 4. Задержка 2 минуты берёт минуту ещё дальше.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), (99.0, 99.0, 99.0, 99.0), (97.0, 97.0, 97.0, 97.0)])
    if not close(ep(b, lag=2)["итог_доля"], -(LEV * 0.03 + FEE)):
        fails.append(f"задержка 2 берёт не ту минуту: {ep(b, lag=2)}")

    # 5. Статическая просадка 6 % связывает, когда снимок на полночь НИЖЕ капитала места:
    #    дневная линия 95×0.97 = 92.15 ниже статической 94, значит рубит статическая.
    b = bar([flat, (99.0, 99.0, 97.0, 97.5), flat])
    r = ep(b, lag=0, snapshot=95.0)
    if not (r["пробито"] and close(r["линия_доля"], -MDD)):
        fails.append(f"статическая линия 6 % не связывает при снимке 95: {r}")

    # 6. Дневная линия считается от СНИМКА, а не от капитала: снимок 104 ⇒ линия 100.88 уже выше
    #    эквити 100, места в сделке быть не может.
    if ep(bar([flat, flat]), snapshot=104.0).get("вход") is not None:
        fails.append("вход разрешён, когда линия уже пробита до входа")

    # 7. Ликвидация биржей: глубокий ход обрезает убыток уровнем ликвидации, а не ходом цены.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), (50.0, 50.0, 50.0, 50.0)])
    r = ep(b, lag=1)
    p_liq = PS.liq_price(100.0, 1, LEV, MM)
    want = -(1.0 - (1.0 + LEV * (p_liq / 100.0 - 1.0)) + FEE)
    if not (r["ликвидация"] and close(r["итог_доля"], want)):
        fails.append(f"убыток не обрезан уровнем ликвидации: {r}, ждали {want}")
    if r["итог_доля"] < -1.0:
        fails.append(f"место потеряло больше своего капитала: {r['итог_доля']}")

    # 7а. Без поддерживающей маржи (--mm 0) уровень ликвидации совпадает с нулём эквити: убыток
    #     обязан упереться ровно в капитал места. Комиссия сверх нуля означала бы долг пула бирже.
    r0 = ep(b, lag=1, mm=0.0)
    if not close(r0["итог_доля"], -1.0):
        fails.append(f"при mm=0 место теряет не ровно свой капитал: {r0['итог_доля']}")

    # 7б. Комиссия не делает долг и без ликвидации: при mm=0 выход чуть выше цены нулевого эквити
    #     оставляет крохи, меньше комиссии — место теряет ровно капитал, не больше, и флага ликвидации нет.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), (80.01, 80.02, 80.01, 80.01)])
    r = ep(b, lag=1, mm=0.0)
    if r["ликвидация"] or not close(r["итог_доля"], -1.0):
        fails.append(f"без ликвидации комиссия увела место в долг или подняла флаг: {r}")

    # 8. Уровень ликвидации по определению: эквити / номинал = поддерживающая маржа.
    for side in (1, -1):
        p = PS.liq_price(100.0, side, LEV, MM)
        eq = 1.0 + LEV * side * (p / 100.0 - 1.0)
        if not close(eq / (LEV * p / 100.0), MM, 1e-12):
            fails.append(f"уровень ликвидации не даёт mm={MM} (сторона {side}): {eq / (LEV * p / 100.0)}")

    # 9. 🔴 Путь до закрытия кончается НА закрытии: при мгновенном стороже минимум минуты пробития
    #    принадлежит уже закрытой позиции. Иначе сторож, успевший на линии, всё равно «ликвидируется».
    b = bar([flat, (99.8, 99.9, 50.0, 99.6), flat])
    r = ep(b, lag=0)
    if r["ликвидация"] or not close(r["итог_доля"], -(DL + FEE)):
        fails.append(f"мгновенный сторож ликвидирован минимумом минуты, в которой его уже нет: {r}")

    # 10. Гэп ЧЕРЕЗ линию: минута открылась ниже линии — даже мгновенный сторож выходит по открытию.
    b = bar([flat, (98.0, 98.0, 97.5, 97.8), flat])
    r = ep(b, lag=0)
    if not close(r["итог_доля"], -(LEV * 0.02 + FEE)):
        fails.append(f"гэп через линию исполнен по линии, а не по открытию: {r}")
    if r["перелёт_доля"] <= FEE:
        fails.append("гэп через линию не даёт перелёта")

    # 11. Шорт зеркален: линия сверху, рубит рост цены.
    b = bar([flat, (100.2, 101.0, 100.1, 100.8), flat])
    r = ep(b, side=-1, lag=0)
    if not (r["пробито"] and close(r["итог_доля"], -(DL + FEE))):
        fails.append(f"шорт не рубится ростом цены: {r}")
    if ep(bar([flat, (99.0, 99.0, 98.0, 98.0), flat]), side=-1, lag=0)["пробито"]:
        fails.append("шорт пробит падением цены")

    # 12. Правило не пробито — держим до конца суток, платим только комиссию.
    b = bar([flat, (100.0, 100.1, 99.9, 100.0), (100.0, 100.0, 100.0, 100.0)])
    r = ep(b, lag=1)
    if r["пробито"] or not close(r["итог_доля"], -FEE):
        fails.append(f"без пробития правила место что-то потеряло: {r}")

    # 13. Прибыльная сделка не считается пробитием и не даёт перелёта.
    b = bar([flat, (101.0, 101.0, 100.9, 101.0), (102.0, 102.0, 102.0, 102.0)])
    r = ep(b, lag=1)
    if r["пробито"] or r["итог_доля"] <= 0:
        fails.append(f"растущий лонг закрыт по правилу: {r}")

    # 13а. 🔴 Закрытие по открытию следующей минуты — НЕ верхняя граница: на отскоке место выходит
    #      лучше линии, а бывает и в плюс. Так было с BTC 10.10.2025 в минуту 21:18.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), (101.0, 101.0, 101.0, 101.0)])
    r = ep(b, lag=1)
    if not (r["пробито"] and r["итог_доля"] > 0):
        fails.append(f"выход на отскоке не даёт места в плюсе — граница считается неверно: {r}")

    # 13б. Режим worst берёт худшую цену ВСЕГО окна задержки, а не только минуты выхода: здесь
    #      худшая цена стоит в минуте ПРОБИТИЯ, и взять её обязан именно он.
    b = bar([flat, (99.8, 99.9, 90.0, 99.6), (99.5, 99.5, 99.0, 99.5)])
    r_open = ep(b, lag=1, exec_mode="open")
    r_worst = ep(b, lag=1, exec_mode="worst")
    if not close(r_open["итог_доля"], -(LEV * 0.005 + FEE)):
        fails.append(f"режим open взял не открытие минуты k: {r_open}")
    if not close(r_worst["итог_доля"], -(LEV * 0.10 + FEE)):
        fails.append(f"режим worst взял не худшую цену окна: {r_worst}")
    if not r_worst["перелёт_доля"] > r_open["перелёт_доля"]:
        fails.append("режим worst не хуже режима open")

    # 13в. 🔴 Путь до ликвидации кончается на цене ВЫХОДА: если сторож вышел ниже уровня
    #      ликвидации, значит биржа успела раньше. Верхняя граница (`worst`) — место теряет всё:
    #      резервная ликвидация маржу не возвращает (документация Hyperliquid).
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), (99.5, 99.5, 70.0, 99.5)])
    r = ep(b, lag=1, exec_mode="worst")
    if not (r["ликвидация"] and close(r["итог_доля"], -1.0)):
        fails.append(f"верхняя граница: ликвидированное место теряет не весь капитал: {r}")
    # 13г. Нижняя граница (`open`) при той же ликвидации оставляет месту поддерживающую маржу
    #      минус комиссию: ликвидация через книгу возвращает остаток обеспечения.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), (50.0, 50.0, 50.0, 50.0)])
    r = ep(b, lag=1, exec_mode="open")
    p_liq2 = PS.liq_price(100.0, 1, LEV, MM)
    want2 = -(1.0 - (1.0 + LEV * (p_liq2 / 100.0 - 1.0)) + FEE)
    if not (r["ликвидация"] and close(r["итог_доля"], want2)):
        fails.append(f"нижняя граница: ликвидированное место не оставляет маржу: {r}, ждали {want2}")
    if not (-1.0 < want2 < -0.9):
        fails.append(f"фикстура: остаток маржи при 5× и 2 % должен быть около 8 %: {want2}")

    # 18. 🔴 Край суток. Линия пробита в ПОСЛЕДНЕЙ минуте суток при задержке 1: минуты для выхода нет,
    #     а её открытие стоит ДО пробития и выходом быть не может. Выход — по закрытию последней минуты.
    b = bar([flat, flat, flat, (99.8, 99.9, 99.0, 99.3)])
    r = ep(b, lag=1)
    if not (r["пробито"] and close(r["итог_доля"], -(LEV * 0.007 + FEE))):
        fails.append(f"край суток: выход не по закрытию последней минуты (99,3): {r}")
    if not (r["выход"] == int(b["ts"][3]) and r["минут_до_выхода"] == 3):
        fails.append(f"край суток: минута выхода не последняя: {r}")
    # 18а. Путь до выхода проходит последнюю минуту целиком: её низ ниже уровня ликвидации — биржа
    #      успела раньше, место ликвидировано (в режиме open остаток маржи, флаг стоит).
    b = bar([flat, flat, flat, (99.8, 99.9, 50.0, 99.3)])
    r = ep(b, lag=1)
    if not (r["ликвидация"] and close(r["итог_доля"], want2)):
        fails.append(f"край суток: низ последней минуты не входит в путь до ликвидации: {r}")
    # 18б. То же при задержке 2 и пробитии за минуту до конца: минуты j + 2 нет — выход по закрытию
    #      последней минуты, не по её открытию.
    b = bar([flat, flat, (99.8, 99.9, 99.0, 99.6), (99.7, 99.8, 99.5, 99.5)])
    r = ep(b, lag=2)
    if not close(r["итог_доля"], -(LEV * 0.005 + FEE)):
        fails.append(f"край суток при задержке 2: выход не по закрытию последней минуты (99,5): {r}")
    # 18в. Пробитие не в последней минуте — прежнее правило: открытие минуты j + lag.
    b = bar([flat, (99.8, 99.9, 99.0, 99.6), (99.2, 99.3, 99.0, 99.1), (98.0, 98.0, 98.0, 98.0)])
    r = ep(b, lag=1)
    if not close(r["итог_доля"], -(LEV * 0.008 + FEE)):
        fails.append(f"обычная минута: выход не по открытию следующей (99,2): {r}")

    # 14. Сводка: перелёт берётся только по пробитым эпизодам, доля «хуже просадки» — по всем.
    s = PS.summarise([{"пробито": True, "итог_доля": -0.10, "перелёт_доля": 0.04, "ликвидация": False},
                      {"пробито": False, "итог_доля": -0.001, "перелёт_доля": 0.0, "ликвидация": False}],
                     MDD, "проба")
    if not (close(s["перелёт_средн_пп"], 4.0) and close(s["хуже_просадки_%"], 50.0)):
        fails.append(f"сводка считает перелёт или долю хуже просадки не по тем эпизодам: {s}")

    with tempfile.TemporaryDirectory() as td:
        d = Path(td)
        PS.DATA = str(d)
        # Сутки: ровная ночь, затем обвал на 20 % за минуту 61 и возврат.
        crash = [flat] * 61 + [(100.0, 100.0, 80.0, 82.0)] + [(82.0, 82.0, 82.0, 82.0)] * 60
        calm = [flat] * 122
        for s in ("AAAUSDT", "BBBUSDT", "CCCUSDT", "DDDUSDT", "EEEUSDT"):
            write_npz(d, s, crash)
        write_npz(d, "ZZZUSDT", calm, T0 + 86400)
        write_npz(d, "TWOUSDT", crash + [flat] * (1640 - len(crash)), T0)   # ряд идёт в следующие сутки

        # 15. Сутки грузятся окном UTC и только своим: ряд длиннее суток режется по верхней границе.
        if PS.load_day("AAAUSDT", T0 + 86400) is not None:
            fails.append("load_day отдал сутки, которых у монеты нет")
        if len(PS.load_day("AAAUSDT", T0)["o"]) != len(crash):
            fails.append("load_day режет сутки")
        two = PS.load_day("TWOUSDT", T0)
        if len(two["o"]) != 1440:
            fails.append(f"load_day взял не одни сутки: минут {len(two['o'])}")

        # 16. Худшие сутки — по средней просадке от открытия: обвальные раньше спокойных.
        w = PS.worst_days(["AAAUSDT", "ZZZUSDT"], "2025-10-10", 2)
        if w[0] != "2025-10-10":
            fails.append(f"худшие сутки отсортированы не по просадке: {w}")

        # 17. Пул: пять мест на пяти монетах, обвал общий — пробивает все пять, убыток складывается
        #     по капиталу мест, а не по числу мест.
        rep = PS.seats_report(["2025-10-10"], ["AAAUSDT", "BBBUSDT", "CCCUSDT", "DDDUSDT", "EEEUSDT"],
                              side=1, lev=LEV, daily_loss=DL, max_dd=MDD, lag=1, taker_bps=TAKER,
                              mm=MM, mode="minute")
        if len(rep) != 1:
            fails.append(f"отчёт по пулу пуст: {rep}")
        else:
            r = rep[0]
            if r["мест_пробито_в_худшем"] != 5:
                fails.append(f"общий обвал пробил не все пять мест: {r}")
            worst_share = r["худший_убыток_%_капитала_мест"] / 100.0
            per_seat = LEV * 0.20 + FEE                     # ход 20 % при плече 5 обрежется ликвидацией
            cap = 1.0 - (1.0 + LEV * (PS.liq_price(100.0, 1, LEV, MM) / 100.0 - 1.0)) + FEE
            if not close(worst_share, min(per_seat, cap), 5e-3):
                fails.append(f"убыток пула не равен убытку мест: {worst_share} против {min(per_seat, cap)}")
            if r["все_пять_пробиты_%"] < 50.0:
                fails.append(f"общий обвал не виден как одновременное пробитие: {r}")

        # 19. 🔴 Места сводятся по ОТМЕТКЕ ВРЕМЕНИ, а не по номеру бара. У пятой монеты пропущена
        #     минута 30: её обвальный бар стоит под номером 60, у остальных — под 61.
        gap = crash[:30] + crash[31:]
        write_npz(d, "EEEUSDT", gap, ts=[T0 + k * 60 for k in range(len(crash)) if k != 30])
        getattr(PS, "_CSV_CACHE", {}).clear()                          # у оригинала инструмента кеша нет
        five = ["AAAUSDT", "BBBUSDT", "CCCUSDT", "DDDUSDT", "EEEUSDT"]
        bars_ = {s: PS.load_day(s, T0) for s in five}
        mins = PS.entry_minutes(bars_, T0, "minute")
        if len(mins) != len(crash) - 1 or any(t == T0 + 30 * 60 for t, _ in mins):
            fails.append(f"минуты входа — не пересечение по всем монетам: {len(mins)}")
        if mins and mins[30][1] != {"AAAUSDT": 31, "BBBUSDT": 31, "CCCUSDT": 31, "DDDUSDT": 31, "EEEUSDT": 30}:
            fails.append(f"индексы баров на одну отметку разошлись с монетами: {mins[30]}")
        hours = PS.entry_minutes(bars_, T0, "hour")
        if [t for t, _ in hours] != [T0, T0 + 3600, T0 + 7200]:
            fails.append(f"час-режим берёт не ровные часы: {[t for t, _ in hours]}")
        rep = PS.seats_report(["2025-10-10"], five, side=1, lev=LEV, daily_loss=DL, max_dd=MDD, lag=1,
                              taker_bps=TAKER, mm=MM, mode="minute")
        r = rep[0] if rep else {}
        if sum(r.get("пробито_мест_распределение", {}).values()) != len(crash) - 1:
            fails.append(f"входов пула не столько, сколько общих минут: {r.get('пробито_мест_распределение')}")
        # 19а. Сторож проводки: отчёт обязан брать индексы КАЖДОЙ монеты из entry_minutes. Подставная
        #      функция даёт одну минуту 01:01 с индексами 61 у четырёх монет и 60 у пятой (её обвальный
        #      бар); отчёт с собственным номером бара взял бы у пятой бар 61 — уже после обвала.
        real = PS.entry_minutes
        PS.entry_minutes = lambda bars, t0, mode: [(T0 + 61 * 60, {s: (60 if s == "EEEUSDT" else 61) for s in bars})]
        try:
            rep = PS.seats_report(["2025-10-10"], five, side=1, lev=LEV, daily_loss=DL, max_dd=MDD, lag=1,
                                  taker_bps=TAKER, mm=MM, mode="minute")
        finally:
            PS.entry_minutes = real
        r = rep[0] if rep else {}
        if r.get("мест_пробито_в_худшем") != 5 or r.get("худший_вход") != "01:01":
            fails.append(f"отчёт не берёт индексы монет из entry_minutes: вход {r.get('худший_вход')}, "
                         f"пробито {r.get('мест_пробито_в_худшем')} из 5")

        # 24. Плечо у каждого места своё, по порядку мест (правило плеча задаёт его по монете), и доля капитала
        #     мест не зависит от их размера. При плече 2 обвал на 20 % места не ликвидирует: выход по открытию
        #     следующей минуты, 82, это −18 % цены; при плече 5 минимум минуты, 80, ниже цены ликвидации, и место
        #     снимает биржа.
        def seat(lev):
            p_liq = PS.liq_price(100.0, 1, lev, MM)
            p_out = p_liq if p_liq >= 80.0 else 82.0
            return 1.0 - (1.0 + lev * (p_out / 100.0 - 1.0)) + TAKER / 1e4 * lev
        report = lambda **kw: PS.seats_report(["2025-10-10"], five, side=1, lev=LEV, daily_loss=DL, max_dd=MDD, lag=1,
                                              taker_bps=TAKER, mm=MM, mode="minute", **kw)[0]
        two = report(seat_levs=[2.0] * 5)
        if not close(two["худший_убыток_%_капитала_мест"] / 100.0, seat(2.0), 5e-4) or two["мест_ликвидировано_в_худшем"]:
            fails.append(f"плечо мест не берётся из seat_levs: {two['худший_убыток_%_капитала_мест']} % "
                         f"против {seat(2.0) * 100:.2f} %")
        mixed = report(seat_levs=[2.0, LEV, LEV, LEV, LEV])
        want = (50 * seat(2.0) + 40 * seat(LEV)) / 90
        if not close(mixed["худший_убыток_%_капитала_мест"] / 100.0, want, 5e-4) or mixed["мест_ликвидировано_в_худшем"] != 4:
            fails.append(f"плечо не у своего места: {mixed['худший_убыток_%_капитала_мест']} % против {want * 100:.2f} %, "
                         f"ликвидировано {mixed['мест_ликвидировано_в_худшем']} из 4")
        base = report()
        small = report(seats=tuple(F * 8 / 9 for F in PS.POOL_SEATS))
        if (small["худший_убыток_%_капитала_мест"] != base["худший_убыток_%_капитала_мест"]
                or abs(small["худший_убыток_usd"] - base["худший_убыток_usd"] * 8 / 9) > 1):
            fails.append(f"места поменьше дали другую долю или те же деньги: {small['худший_убыток_%_капитала_мест']} % "
                         f"${small['худший_убыток_usd']} против {base['худший_убыток_%_капитала_мест']} % "
                         f"${base['худший_убыток_usd']}")
        # Доля пула — только когда пул назван, и от всего пула вместе с запасом, а не от капитала мест.
        whole = report(pool_usd=100_000.0)
        if "худший_убыток_%_пула" in base or not close(whole.get("худший_убыток_%_пула", 0.0),
                                                        whole["худший_убыток_usd"] / 1000.0, 0.051):
            fails.append(f"доля пула не от пула: {whole.get('худший_убыток_%_пула')} % при убытке "
                         f"${whole['худший_убыток_usd']} на пул $100 тыс.")
        try:
            report(seat_levs=[2.0] * 4)
            fails.append("плеч меньше, чем мест, а отчёт посчитал")
        except SystemExit:
            pass
        for bad in ({"seat_levs": [2.0, 2.0, 0.0, 2.0, 2.0]}, {"seat_levs": [2.0, -5.0, 2.0, 2.0, 2.0]},
                    {"seats": (50_000.0, 25_000.0, 5_000.0, -5_000.0, 5_000.0)}):
            try:
                PS.seats_report(["2025-10-10"], five, side=1, lev=LEV, daily_loss=DL, max_dd=MDD, lag=1,
                                taker_bps=TAKER, mm=MM, mode="minute", **bad)
                fails.append(f"плечо или капитал места не больше нуля, а отчёт посчитал: {bad}")
            except SystemExit:
                pass

        # 20. 🔴 Задержка выхода — по ВРЕМЕНИ, не по номеру бара. Минуты 3 нет: пробитие в минуте 2,
        #     задержка 2 → выход в минуте 4 (бар № 3), а не в баре № 4 (минута 5).
        gapped = bar([flat, flat, (99.8, 99.9, 99.0, 99.6), (97.0, 97.0, 97.0, 97.0), (95.0, 95.0, 95.0, 95.0)],
                     )
        gapped["ts"] = np.array([T0 + m * 60 for m in (0, 1, 2, 4, 5)], dtype=np.int64)
        r = ep(gapped, lag=2)
        if not (close(r["итог_доля"], -(LEV * 0.03 + FEE)) and r["выход"] == T0 + 4 * 60 and r["минут_до_выхода"] == 4):
            fails.append(f"задержка считается по номеру бара, а не по времени: {r}")
        # 20а. Задержка 1, а минуты 3 нет: выход — первая минута после задержки, которую сторож увидит (минута 4).
        r = ep(gapped, lag=1)
        if not (close(r["итог_доля"], -(LEV * 0.03 + FEE)) and r["выход"] == T0 + 4 * 60):
            fails.append(f"при пропущенной минуте выхода не взята первая следующая: {r}")
        # 20б. Путь до ликвидации при задержке по времени проходит только бары ДО выхода: низ бара № 4
        #      (минута 5, после выхода) позиции не принадлежит.
        gapped2 = bar([flat, flat, (99.8, 99.9, 99.0, 99.6), (97.0, 97.0, 97.0, 97.0), (95.0, 95.0, 10.0, 95.0)])
        gapped2["ts"] = gapped["ts"]
        r = ep(gapped2, lag=2)
        if r["ликвидация"]:
            fails.append(f"низ бара после выхода засчитан позиции: {r}")

        # 21. 🔴 Почасовые входы — по отметке времени: у ряда без минуты 30 бар № 60 — это минута 01:01,
        #     а вход обязан быть в 01:00 (бар № 59).
        ts_gap = np.array([T0 + m * 60 for m in range(122) if m != 30], dtype=np.int64)
        idx = PS.entry_indices(ts_gap, T0, "hour")
        if idx != [0, 59, 119]:
            fails.append(f"почасовые входы по номеру бара, а не по времени: {idx}")
        if PS.entry_indices(ts_gap, T0, "minute") != list(range(121)):
            fails.append("минутные входы — не все бары")
        # 21а. Сторож проводки: run() берёт входы из entry_indices. Подставная функция даёт один вход
        #      (бар № 59); в строке обязан быть ровно один вход.
        real = PS.entry_indices
        PS.entry_indices = lambda ts, t0, mode: [59]
        try:
            rows, eps_ = PS.run(["2025-10-10"], ["AAAUSDT"], side=1, lev=LEV, daily_loss=DL, max_dd=MDD, lag=1,
                                taker_bps=TAKER, mm=MM, mode="hour")
        finally:
            PS.entry_indices = real
        if not (rows and rows[0]["входов"] == 1 and len(eps_) == 1 and eps_[0]["вход"] == T0 + 59 * 60):
            fails.append(f"run() не берёт входы из entry_indices: {rows and rows[0]['входов']}")

        # 22. 🔴 Сторож загрузчика: повтор минуты или беспорядок — отказ с именем монеты, а не счёт.
        write_npz(d, "DUPUSDT", [flat] * 5, ts=[T0, T0 + 60, T0 + 60, T0 + 180, T0 + 240])
        write_npz(d, "MIXUSDT", [flat] * 5, ts=[T0, T0 + 120, T0 + 60, T0 + 180, T0 + 240])
        for sym in ("DUPUSDT", "MIXUSDT"):
            getattr(PS, "_CSV_CACHE", {}).clear()
            try:
                PS.load_day(sym, T0)
                fails.append(f"{sym}: ряд с повтором/беспорядком минут принят молча")
            except SystemExit as e:
                if sym not in str(e):
                    fails.append(f"{sym}: отказ не называет монету: {e}")
        getattr(PS, "_CSV_CACHE", {}).clear()

    # 23. Докстринг seats_report не обещает «одновременных» пробитий: места пробивают в свои минуты.
    doc = PS.seats_report.__doc__ or ""
    if "пробивает линию одновременно" in doc or "не одновременно" not in doc:
        fails.append("докстринг seats_report обещает одновременные пробития")

    print(f"проверок в файле: 37 · провалов: {len(fails)}")
    for f in fails:
        print("•", f)                                       # «•» читает стенд поломок mut_pool_stress.py
    return 1 if fails else 0


